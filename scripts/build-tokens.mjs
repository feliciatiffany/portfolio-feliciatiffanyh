// Reads tokens/colors.json (W3C design tokens) and writes CSS variables plus a token reference.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tree = JSON.parse(readFileSync(resolve(root, "tokens/colors.json"), "utf8"));

function walk(node, path = []) {
  const leaves = [];
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (val && typeof val === "object" && "$value" in val) {
      leaves.push({
        name: [...path, key].join("-"),
        value: String(val.$value),
        description: val.$description || "",
      });
    } else if (val && typeof val === "object") {
      leaves.push(...walk(val, [...path, key]));
    }
  }
  return leaves;
}

const tokens = walk(tree);
const byName = new Map(tokens.map((t) => [t.name, t]));

function substitute(value, stack = []) {
  return value.replace(/\{([a-z0-9.-]+)\}/gi, (_, ref) => {
    const name = ref.replaceAll(".", "-");
    if (stack.includes(name)) throw new Error(`Token cycle at ${name}`);
    const token = byName.get(name);
    if (!token) throw new Error(`Missing token {${ref}}`);
    return substitute(token.value, [...stack, name]);
  });
}

function toCss(value) {
  return value.replace(/\{([a-z0-9.-]+)\}/gi, (_, ref) => {
    const name = ref.replaceAll(".", "-");
    if (!byName.has(name)) throw new Error(`Missing token {${ref}}`);
    return `var(--${name})`;
  });
}

const resolved = tokens.map((t) => ({
  ...t,
  hex: substitute(t.value),
  css: toCss(t.value),
}));

const washes = resolved
  .filter((t) => t.name.startsWith("color-accent-") || t.name.startsWith("color-surface-"))
  .map((t) => ({
    name: t.name.replace("color-accent-", "color-wash-").replace("color-surface-", "color-wash-"),
    hex: `13% of ${t.hex}`,
    css: `color-mix(in srgb, var(--${t.name}) 13%, transparent)`,
    description: `Soft wash of ${t.name}`,
  }));

const lines = [
  "/* Generated from tokens/colors.json. Do not edit. Run: npm run tokens */",
  ":root {",
  ...resolved.map((t) => `  --${t.name}: ${t.css};`),
  ...washes.map((t) => `  --${t.name}: ${t.css};`),
  "}",
  "",
];

const cssPath = resolve(root, "src/style/tokens.css");
mkdirSync(dirname(cssPath), { recursive: true });
writeFileSync(cssPath, lines.join("\n"));

const rows = [...resolved, ...washes]
  .map((t) => `| \`--${t.name}\` | ${t.description} | ${t.hex} |`)
  .join("\n");

const doc = `# Color tokens

Generated from \`tokens/colors.json\`. Do not edit this file.

Components use semantic names. Palette roles keep the \`--color-*\` prefix. The shadcn roles (\`--background\`, \`--foreground\`, \`--primary\`, \`--muted-foreground\`, \`--accent\`, \`--border\`, \`--ring\`, and the rest) are the names to use for text, surfaces, actions, and focus. Base swatches exist only so a role can point at them.

| Token | Use | Value |
| --- | --- | --- |
${rows}
`;

const docPath = resolve(root, "docs/tokens.md");
mkdirSync(dirname(docPath), { recursive: true });
writeFileSync(docPath, doc);

console.log(`Wrote ${resolved.length} tokens and ${washes.length} washes.`);
